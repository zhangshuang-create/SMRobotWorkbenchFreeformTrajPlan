#pragma once

#include "TrajOptimization_global.h"
#include <TrajOptimizationData/TrajOptimizationData.h>
#include <GeneralData/GeneralData.h>
#include <OptSafeTrajData/OptSafeTrajData.h>
#include <string>
#include <vector>
#include <functional>
namespace ModelTrajPlan
{
    // ========== Core interface of trajectory-optimization algorithms ==========
    // All interfaces operate on TrajOptimizationData
    // Provides robot initialization, model loading, trajectory processing, collision detection, etc.
    class TrajOptimization_SHAREDLIB TrajOptimizationAlgorithm
    {
    public:
        // === Robot-system initialization ===
        // Initialize robot system, requiring at least 2 robot paths
        static bool initializeRobotSystem(
            TrajOptimizationData& data,
            const std::vector<std::string>& robot_paths);

        // === Model-loading interfaces ===
        // Load original model (workpiece)
        static bool loadOriginalModel(
            TrajOptimizationData& data,
            const std::string& file_path);

        // Load actual model (tool / end-effector)
        static bool loadActualModel(
            TrajOptimizationData& data,
            const std::string& file_path);

        // === Trajectory-loading interfaces ===
        // Load trajectory from file
        static bool loadTrajectoryFromFile(
            TrajOptimizationData& data,
            const std::string& file_path);

        // Load trajectory data from GeneralData
        static bool loadTrajectoryFromGeneralData(
            TrajOptimizationData& data,
            const GeneralData& generalData);

        // === Transformation-matrix operations ===
        // Set trajectory transformation matrix
        static void setTransformMatrix(
            TrajOptimizationData& data,
            const Eigen::Matrix4d& matrix);

        // Auto-calculate transformation matrix (ICP registration)
        static bool autoCalculateTransform(
            TrajOptimizationData& data);

        // === Trajectory transformation ===
        // Execute trajectory transformation
        static bool transformTrajectory(
            TrajOptimizationData& data);

        // === Collision detection ===
        // Initialize collision detector
        static bool initCollision(
            TrajOptimizationData& data);

        // Set collision visualization
        static void setCollisionVisualization(
            TrajOptimizationData& data,
            bool enabled);

        // Start collision detection
        static bool startCollisionDetection(
            TrajOptimizationData& data);

        // Stop collision detection
        static void stopCollisionDetection(
            TrajOptimizationData& data);

        // Check whether collision currently exists
        static bool isCollision(
            TrajOptimizationData& data);

        // === Tolerance computation ===
        // Trajectory-tolerance computation with progress callback
        static bool computeTrajectoryToleranceWithProgress(
            TrajOptimizationData& data,
            const ToleranceLimitConfig& tol_limit,
            std::function<void(int, int, const std::string&)> progressCallback);

        // === Trajectory export ===
        // Export transformed trajectory
        static bool exportTransformedTrajectory(
            TrajOptimizationData& data,
            const std::string& file_path);

        // Export toleranced trajectory (compatible with standard trajectory format)
        static bool exportTolerancedTrajectory(
            TrajOptimizationData& data,
            const std::string& file_path);

        // Export readable file in PublicTrajectoryPoint format
        static bool exportToPublicTrajData(
            TrajOptimizationData& data,
            const std::string& file_path);

        // Convert TolerancedTrajectoryPoint to PublicTrajectoryPoint
        // If the point is generated by RRT, generation_method and backup_points will be set
        static PublicData::OptTrajectoryPoint convertToPublicTrajectoryPoint(
            TrajOptimizationData& data,
            double timestamp,
            const TolerancedTrajectoryPoint& tol_point);

        // Convert entire trajectory to map<timestamp, PublicTrajectoryPoint> for PublicTrajData
        // Returned map can be used directly by PublicTrajData::loadFromData()
        static PublicData::OptTrajectoryPoints convertToPublicTrajectoryPoints(
            TrajOptimizationData& data);

        // Export full project (including trajectory, robot models, and config file)
        // project_dir: full path of project directory (including project name)
        // project_name: project name (for config.json)
        // return: true on success, false on failure
        static bool exportProject(
            TrajOptimizationData& data,
            const std::string& project_dir,
            const std::string& project_name);

        // === Visualization interfaces ===
        // Draw scene (requires OpenGL context)
        // Includes workpiece, tool, robots, and trajectory coordinate frames
        static bool draw(TrajOptimizationData& data);

        // === Trajectory coordinate-frame visualization ===
        // Create trajectory-point coordinate-frame models
        static bool createTrajectoryFrames(
            TrajOptimizationData& data,
            float scale = 50.0f);

        // Set trajectory visibility
        static void setTrajectoryVisibility(
            TrajOptimizationData& data,
            bool visible);

        // Draw trajectory coordinate frames
        static bool drawTrajectoryFrames(
            TrajOptimizationData& data);

    private:
        // === Internal helper functions ===
        // Parse trajectory file (internal implementation)
        static bool parseTrajectoryFile(
            TrajOptimizationData& data,
            const std::string& file_path);

    };

}

